//go:generate go run ../cmd/gendoc ../../docs/reference

// referenceHeader marks the files of docs/reference as generated.
const referenceHeader = "<!-- Code generated by internal/cmd/gendoc from the command tree. DO NOT EDIT. Run \"mise run docs\". -->\n\n"

// WriteReference replaces the Markdown files in dir with the command
// reference generated from the command tree.
func WriteReference(dir string) error {
	files, err := referenceFiles()
	if err != nil {
		return err
	}
	old, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return err
	}
	for _, p := range old {
		if err := os.Remove(p); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// referenceRoot builds the command tree as a user sees it, including the
// completion command cobra adds when it runs.
func referenceRoot() *cobra.Command {
	f := &cmdutil.Factory{IO: &cmdutil.IOStreams{}, Getenv: func(string) string { return "" }}
	root := NewRootCmd(f)
	// The default of --no-input comes from the environment.
	if fl := root.PersistentFlags().Lookup("no-input"); fl != nil {
		fl.DefValue = "false"
	}
	root.InitDefaultCompletionCmd()
	return root
}

// referenceFiles returns the files of docs/reference by name: README.md,
// one file per top-level command, and endpoints.md.
func referenceFiles() (map[string][]byte, error) {
	root := referenceRoot()
	files := map[string][]byte{}

	var idx bytes.Buffer
	idx.WriteString(referenceHeader)
	idx.WriteString("# mcrl command reference\n\n")
	writeHelpBlock(&idx, root, false)
	for _, g := range root.Groups() {
		fmt.Fprintf(&idx, "## %s\n\n| Command | Description |\n|---|---|\n", strings.TrimSuffix(g.Title, ":"))
		for _, c := range root.Commands() {
			if c.GroupID == g.ID && c.IsAvailableCommand() {
				fmt.Fprintf(&idx, "| [`%s`](%s) | %s |\n", c.Name(), referenceFile(c), c.Short)
			}
		}
		idx.WriteString("\n")
	}
	idx.WriteString("## Help topics\n\n")
	for _, c := range root.Commands() {
		if c.Hidden && c.Runnable() && len(c.Commands()) == 0 {
			fmt.Fprintf(&idx, "### mcrl help %s\n\n```text\n%s\n```\n\n", c.Name(), strings.TrimSpace(c.Long))
		}
	}
	idx.WriteString("## API endpoints\n\n[endpoints.md](endpoints.md) maps every endpoint of the Mackerel API to the commands that call it.\n")
	files["README.md"] = idx.Bytes()

	for _, c := range root.Commands() {
		if !c.IsAvailableCommand() {
			continue
		}
		var b bytes.Buffer
		b.WriteString(referenceHeader)
		fmt.Fprintf(&b, "# %s\n\n[Command reference](README.md)\n\n", c.CommandPath())
		writeCommand(&b, c, true)
		files[referenceFile(c)] = bytes.TrimRight(b.Bytes(), "\n")
		files[referenceFile(c)] = append(files[referenceFile(c)], '\n')
	}

	ep, err := endpointReference(root)
	if err != nil {
		return nil, err
	}
	files["endpoints.md"] = ep
	return files, nil
}

// referenceFile is the file that documents a command and its subcommands.
func referenceFile(c *cobra.Command) string {
	for c.HasParent() && c.Parent().HasParent() {
		c = c.Parent()
	}
	return c.Name() + ".md"
}

// referenceLink links to the section of a command.
func referenceLink(c *cobra.Command) string {
	return referenceFile(c) + "#" + strings.ReplaceAll(c.CommandPath(), " ", "-")
}

func writeCommand(b *bytes.Buffer, c *cobra.Command, top bool) {
	if !top {
		fmt.Fprintf(b, "## %s\n\n", c.CommandPath())
	}
	b.WriteString(strings.TrimSuffix(c.Short, ".") + ".\n\n")
	writeHelpBlock(b, c, true)
	var subs []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() {
			subs = append(subs, s)
		}
	}
	if len(subs) > 0 {
		b.WriteString("| Subcommand | Description |\n|---|---|\n")
		for _, s := range subs {
			fmt.Fprintf(b, "| [`%s`](#%s) | %s |\n", strings.TrimPrefix(s.CommandPath(), "mcrl "), strings.ReplaceAll(s.CommandPath(), " ", "-"), s.Short)
		}
		b.WriteString("\n")
	}
	for _, s := range subs {
		writeCommand(b, s, false)
	}
}

// writeHelpBlock writes what "--help" shows, without the global flags, as a
// text block (help texts contain <placeholders> that Markdown would drop).
func writeHelpBlock(b *bytes.Buffer, c *cobra.Command, withUsage bool) {
	var parts []string
	if withUsage && c.Runnable() && !c.HasAvailableSubCommands() {
		parts = append(parts, "Usage:\n  "+c.UseLine())
	}
	if len(c.Aliases) > 0 {
		parts = append(parts, "Aliases:\n  "+strings.Join(append([]string{c.Name()}, c.Aliases...), ", "))
	}
	if long := strings.TrimSpace(c.Long); long != "" {
		parts = append(parts, long)
	}
	if ex := strings.TrimRight(c.Example, " \n"); ex != "" {
		parts = append(parts, "Examples:\n"+ex)
	}
	if fl := c.NonInheritedFlags(); fl.HasAvailableFlags() {
		title := "Flags:"
		if !c.HasParent() {
			title = "Global flags:"
		}
		parts = append(parts, title+"\n"+strings.TrimRight(fl.FlagUsages(), "\n"))
	}
	if len(parts) == 0 {
		return
	}
	fmt.Fprintf(b, "```text\n%s\n```\n\n", strings.Join(parts, "\n\n"))
}

// endpointReference lists every API endpoint with the commands that call it.
func endpointReference(root *cobra.Command) ([]byte, error) {
	uses, errs := endpointCoverage(root)
	if len(errs) > 0 {
		return nil, errs[0]
	}
	covered := 0
	for _, u := range uses {
		if len(u.Commands) > 0 {
			covered++
		}
	}
	var b bytes.Buffer
	b.WriteString(referenceHeader)
	b.WriteString("# API endpoints\n\n[Command reference](README.md)\n\n")
	fmt.Fprintf(&b, "Every endpoint in the index of the [Mackerel API documents](https://mackerel.io/api-docs/) and the commands that call it: %d of %d endpoints have a command. ", covered, len(uses))
	b.WriteString("Any endpoint can also be called with `mcrl api`.\n")
	section := ""
	for _, u := range uses {
		if s := u.Endpoint.Section(); s != section {
			section = s
			fmt.Fprintf(&b, "\n## %s\n\n| Endpoint | API key permission | Commands |\n|---|---|---|\n", s)
		}
		var cmds []string
		for _, c := range u.Commands {
			cmds = append(cmds, fmt.Sprintf("[`%s`](%s)", c.CommandPath(), referenceLink(c)))
		}
		if u.LeftToAPI != "" {
			cmds = append(cmds, "none: "+u.LeftToAPI)
		}
		fmt.Fprintf(&b, "| [`%s`](%s) | %s | %s |\n", u.Endpoint, u.Endpoint.DocURL(), u.Endpoint.Perm, strings.Join(cmds, ", "))
	}
	return b.Bytes(), nil
}
